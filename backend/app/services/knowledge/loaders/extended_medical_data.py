async def load_extended_medical_data():
    """加载扩展医学数据到知识库"""
    from app.services.knowledge import KnowledgeService

    knowledge = KnowledgeService.get_instance()
    await knowledge.initialize()

    added_count = 0

    for item in EXTENDED_ICD10_DATA:
        content = f"{item['name']}（{item['code']}）\n{item['content']}"

        metadata = {
            "code": item["code"],
            "name": item["name"],
            "keywords": item["keywords"],
            "category": item["category"],
            "specialty": item["specialty"]
        }

        doc_id = await knowledge.add_document(
            content=content,
            metadata=metadata,
            specialty=item["specialty"],
            source="icd10_extended"
        )

        if doc_id:
            added_count += 1
            print(f"[ExtendedData] 添加: {item['name']} ({item['code']}) - {item['specialty']}")

    print(f"[ExtendedData] 完成，共添加 {added_count} 条数据")

    return added_count


if __name__ == "__main__":
    import asyncio
    asyncio.run(load_extended_medical_data())

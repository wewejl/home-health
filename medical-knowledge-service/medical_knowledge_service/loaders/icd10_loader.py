def load_icd10_documents() -> List[Document]:
    """加载 ICD-10 知识为文档列表"""
    documents = []

    for item in ICD10_KNOWLEDGE_BASE:
        doc = Document(
            content=item["content"].strip(),
            metadata={
                "code": item["code"],
                "name": item["name"],
                "keywords": ",".join(item["keywords"])
            },
            specialty=item["specialty"],
            category="icd10"
        )
        documents.append(doc)

    return documents
